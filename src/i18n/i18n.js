i18n.use(initReactI18next).init({
  resources,
  fallbackLng: "en",
  supportedLngs: ["en", "fr"],

  lng: "en",

  interpolation: {
    escapeValue: false,
  },
});
export function applyUserLanguage(language) {
  const normalizedLanguage = String(language || "")
    .trim()
    .toUpperCase();

  const nextLanguage = normalizedLanguage === "FR" ? "fr" : "en";

  if (i18n.language !== nextLanguage) {
    i18n.changeLanguage(nextLanguage);
  }

  return nextLanguage;
}
export default i18n;
